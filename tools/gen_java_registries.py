def gen_items():
    out = [HEADER, f"package {PACKAGE}.registry;", "",
           "import net.minecraft.world.item.Item;",
           "import net.minecraft.world.item.Rarity;",
           "import net.neoforged.neoforge.registries.DeferredItem;",
           "import net.neoforged.neoforge.registries.DeferredRegister;",
           "",
           f'import static {PACKAGE}.PathwaysMod.MOD_ID;',
           f'import {PACKAGE}.item.OccultItems;',
           "",
           "/** Every item: pathway potions, ingredients, sealed artifacts, occult tools. */",
           "public final class ModItems {",
           "    private ModItems() {}",
           "",
           "    public static final DeferredRegister.Items ITEMS = DeferredRegister.createItems(MOD_ID);",
           ""]
    out.append("    // ---- pathway potions ----")
    for pid, name, pathway, seq, colour, glow, rarity in POTIONS:
        const = "".join(part.capitalize() for part in pid.split("_"))
        out.append(f'    /** {name} - {pathway} Sequence {seq} */')
        out.append(f'    public static final DeferredItem<Item> {const} = ITEMS.register("{pid}",')
        out.append(f'            () -> new OccultItems.PathwayPotionItem(new Item.Properties().stacksTo(4), '
                   f'"{pathway.lower()}", {seq}, 0x{colour.lstrip("#")}, "{glow}"));')
    out.append("")
    out.append("    // ---- supernatural ingredients ----")
    for iid, name, tier, origin, lore in INGREDIENTS:
        const = "".join(part.capitalize() for part in iid.split("_"))
        out.append(f'    /** {name} - {origin} */')
        out.append(f'    public static final DeferredItem<Item> {const} = ITEMS.register("{iid}",')
        out.append(f'            () -> new OccultItems.SimpleLoreItem(new Item.Properties(), {tier}));')
    out.append("")
    out.append("    // ---- sealed artifacts ----")
    for aid, name, rarity, desc, passive, drawback in ARTIFACTS:
        const = "".join(part.capitalize() for part in aid.split("_"))
        cls = ITEM_CLASSES[aid]
        out.append(f'    /** {name} - {desc} */')
        out.append(f'    public static final DeferredItem<Item> {const} = ITEMS.register("{aid}",')
        out.append(f'            () -> new OccultItems.{cls}(new Item.Properties().stacksTo(1)'
                   f'.rarity(Rarity.{rarity_name(rarity)})));')
    out.append("")
    out.append("    // ---- occult tools ----")
    for uid, name, desc in UTILITY_ITEMS:
        const = "".join(part.capitalize() for part in uid.split("_"))
        cls = ITEM_CLASSES[uid]
        out.append(f'    /** {name} - {desc} */')
        out.append(f'    public static final DeferredItem<Item> {const} = ITEMS.register("{uid}",')
        out.append(f'            () -> new OccultItems.{cls}(new Item.Properties().stacksTo(1)));')
    out.append("")
    out.append("    // ---- drops ----")
    out.append('    public static final DeferredItem<Item> CORRUPTED_HEART_DROP = ITEMS.register("corrupted_heart",')
    out.append("            () -> new OccultItems.SimpleLoreItem(new Item.Properties(), 4));")
    out += ["",
            "    private static String rarityName(int tier) {",
            "        return switch (tier) {",
            '            case 2 -> "UNCOMMON";',
            '            case 3 -> "RARE";',
            '            case 4, 5 -> "EPIC";',
            '            default -> "COMMON";',
            "        };",
            "    }",
            "",
            "    public static void register(net.neoforged.bus.api.IEventBus bus) {",
            "        ITEMS.register(bus);",
            "    }",
            "}",
            ""]
    w("registry/ModItems.java", "\n".join(out))


def rarity_name(tier):
    return {1: "COMMON", 2: "UNCOMMON", 3: "RARE", 4: "EPIC", 5: "EPIC"}.get(tier, "COMMON")


