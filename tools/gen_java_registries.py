def gen_sounds_json():
    """Writes assets/pathwaysofthebeyond/sounds.json.

    One entry per registered sound event id. Minecraft resolves sound events by id, so a
    grouped "bank" object silently leaves every SoundEvent unplayable.
    """
    data_dir = os.path.join(ROOT, "src", "main", "resources", "assets", MOD_ID)
    os.makedirs(data_dir, exist_ok=True)
    path = os.path.join(data_dir, "sounds.json")
    payload = {}
    for entry in SOUNDS:
        sound_id = entry[0]
        payload[sound_id] = {
            "subtitle": "sound.pathwaysofthebeyond." + sound_id,
            "sounds": [
                {"name": "pathwaysofthebeyond:" + sound_id, "stream": False}
            ],
        }
    with open(path, "w", encoding="utf-8") as f:
        json.dump(payload, f, indent=2, ensure_ascii=False)
        f.write("\n")
    print("  wrote sounds.json (%d sound events)" % len(payload))

