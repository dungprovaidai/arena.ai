def gen_pathway_data():
    """PathwayData.java: every pathway, sequence, colour, lore line and unlock cost."""
    out = [HEADER, f"package {PACKAGE}.pathway;", "",
           "import java.util.List;", "import java.util.Map;", "",
           "/**",
           " * All pathway / sequence definitions. The Fool pathway is implemented to Sequence 0;",
           " * the other seven are registered with their sequence ladders and potions so they can be",
           " * developed without touching the registry.",
           " */",
           "public final class PathwayData {",
           "    private PathwayData() {}",
           "",
           "    /** One sequence: its index (9 = weakest, 0 = strongest), name, lore and abilities. */",
           "    public record SequenceDef(int sequence, String id, String name, String lore,",
           "                              List<String> abilities, String potionId) {}",
           "",
           "    /** One pathway: identity, colour language, lore and the ten sequences. */",
           "    public record PathwayDef(String id, String displayName, int colour, int accent,",
           "                             String emblem, int deepestImplemented, String lore,",
           "                             List<SequenceDef> sequences) {",
           "        public SequenceDef bySequence(int seq) {",
           "            for (SequenceDef s : sequences) {",
           "                if (s.sequence() == seq) return s;",
           "            }",
           "            return null;",
           "        }",
           "        public int maxSequence() { return deepestImplemented; }",
           "    }",
           "",
           "    // ---- ability ids per sequence (implemented in Abilities.java) ----",
           "    private static final Map<String, List<String>> FOOL_ABILITIES = Map.ofEntries(",
           "            Map.entry(\"seer\", List.of(\"supernatural_sight\", \"ore_sense\", \"danger_premonition\", \"perception\")),",
           "            Map.entry(\"clown\", List.of(\"unnatural_agility\", \"fold_step\", \"dodge_instinct\", \"combat_prediction\")),",
           "            Map.entry(\"magician\", List.of(\"stage_illusion\", \"blink\", \"decoy_double\", \"perception_rewrite\")),",
           "            Map.entry(\"faceless\", List.of(\"wear_face\", \"borrowed_mien\", \"feature_shift\", \"mask_of_nobody\")),",
           "            Map.entry(\"marionettist\", List.of(\"soul_thread_view\", \"bind_puppet\", \"puppet_command\", \"sever_thread\")),",
           "            Map.entry(\"bizarro_sorcerer\", List.of(\"bizarro_copy\", \"reality_warp\", \"twisted_mirage\", \"argument_of_copies\")),",
           "            Map.entry(\"scholar_of_yore\", List.of(\"read_the_stone\", \"memory_echo_runtime\", \"echo_summon\", \"rewind_moment\")),",
           "            Map.entry(\"miracle_invoker\", List.of(\"small_miracle\", \"wish_lantern\", \"rainstorm_of_quiet\", \"debt_of_miracles\")),",
           "            Map.entry(\"attendant_of_mysteries\", List.of(\"forbidden_ward\", \"deep_ritual\", \"astral_walk\", \"authority_to_forbid\")),",
           "            Map.entry(\"the_fool\", List.of(\"between_two_truths\", \"unreality_walk\", \"the_space_between\", \"the_noticing_dawn\"))",
           "    );",
           "",
           "    /** Abilities for pathways that are not yet implemented: registered but inert. */",
           "    private static final List<String> PLACEHOLDER = List.of();",
           "",
           ]
    pathway_blocks = []
    for p in PATHWAYS:
        seq_lines = []
        for idx, (sid, sname, lore) in enumerate(p["sequences"]):
            seq_num = 9 - idx
            potion = next((x[0] for x in POTIONS if x[2] == p["id"] and x[3] == seq_num), None)
            quote = chr(34)
            potion_lit = (quote + potion + quote) if potion else "null"
            lore_esc = lore.replace(chr(34), chr(92) + chr(34))
            # no trailing comma: Java does not allow one in an argument list
            seq_lines.append(
                f'                new SequenceDef({seq_num}, "{sid}", '
                f'"{sname}", "{lore_esc}", ABILITIES_{p["id"].upper()}.get("{sid}"), '
                f'{potion_lit})')
        block = [f'            // ---- {p["name"]} ----',
                 '            new PathwayDef(',
                 f'                    "{p["id"]}", "{p["name"]}", '
                 f'{p["color"].replace("#", "0xFF")}, {p["accent"].replace("#", "0xFF")},',
                 f'                    "{p["emblem"]}", {p["implemented"]},',
                 f'                    "{p["lore"].replace(chr(34), chr(92) + chr(34))}",',
                 '                    List.of(']
        block.append(",\n".join(seq_lines))
        block.append('                    ))')
        pathway_blocks.append("\n".join(block))
    out.append("    public static final List<PathwayDef> ALL = List.of(")
    out.append(",\n".join(pathway_blocks))
    out += ["    );",
            "",
            "    public static PathwayDef byId(String id) {",
            "        for (PathwayDef p : ALL) {",
            "            if (p.id().equals(id)) return p;",
            "        }",
            "        return ALL.get(0);",
            "    }",
            "",
            "    public static PathwayDef byIndex(int index) {",
            "        return ALL.get(Math.max(0, Math.min(ALL.size() - 1, index)));",
            "    }",
            "}",
            ""]
    # placeholder ability maps for the other pathways so the emitted code compiles
    body = "\n".join(out)
    placeholders = []
    for p in PATHWAYS:
        if p["id"] == "fool":
            continue
        entries = ", ".join(f'"{s[0]}"' for s in p["sequences"])
        placeholders.append(f"    private static final Map<String, List<String>> ABILITIES_{p['id'].upper()} = "
                            f"Map.ofEntries({', '.join(f'Map.entry({e}, PLACEHOLDER)' for e in entries.split(', '))});")
    # insert placeholder maps before ALL
    marker = "    public static final List<PathwayDef> ALL = List.of("
    body = body.replace(marker, "\n".join(placeholders) + "\n\n" + marker)
    # ABILITIES_FOOL alias
    body = body.replace("FOOL_ABILITIES", "ABILITIES_FOOL")
    w("pathway/PathwayData.java", body)


def gen_sounds():
    out = [HEADER, f"package {PACKAGE}.registry;", "",
           "import net.minecraft.core.registries.Registries;",
           "import net.minecraft.resources.ResourceLocation;",
           "import net.minecraft.sounds.SoundEvent;",
           "import net.neoforged.neoforge.registries.DeferredHolder;",
           "import net.neoforged.neoforge.registries.DeferredRegister;",
           "",
           f'import static {PACKAGE}.PathwaysMod.MOD_ID;',
           "",
           "/** Every sound in the mod. Files live in assets/" + MOD_ID + "/sounds/*.ogg (procedurally synthesized). */",
           "public final class ModSounds {",
           "    private ModSounds() {}",
           "",
           "    public static final DeferredRegister<SoundEvent> SOUNDS =",
           "            DeferredRegister.create(Registries.SOUND_EVENT, MOD_ID);",
           ""]
    for name, _cat, desc in SOUNDS:
        const = "".join(part.capitalize() for part in name.split("_"))
        out.append(f'    /** {desc} */')
        out.append(f'    public static final DeferredHolder<SoundEvent, SoundEvent> {const} = register("{name}");')
    out += ["",
            "    private static DeferredHolder<SoundEvent, SoundEvent> register(String name) {",
            "        ResourceLocation id = ResourceLocation.fromNamespaceAndPath(MOD_ID, name);",
            "        return SOUNDS.register(name, () -> SoundEvent.createVariableRangeEvent(id));",
            "    }",
            "",
            "    public static void register(net.neoforged.bus.api.IEventBus bus) {",
            "        SOUNDS.register(bus);",
            "    }",
            "}",
            ""]
    w("registry/ModSounds.java", "\n".join(out))


